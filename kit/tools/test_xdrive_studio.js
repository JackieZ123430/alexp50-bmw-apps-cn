'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const X = require(path.join(ROOT, 'apps', 'xdrive_studio', 'logic'));
assert.deepStrictEqual(X.wheelValues({ actualValueRPMWheelFLH:1000, actualValueRPMwheelFRH:1001, actualValueRPMWheelRLH:999, actualValueRPMWheelRRH:1000 }), [1000,1001,999,1000]);
assert.strictEqual(X.wheelValues({ actualValueRPMWheelFLH:65535 }), null);
assert.strictEqual(X.signed16(65535), -1);
assert.ok(X.splitValid(2) && X.splitValid('SIGNALWERT_IST_GUELTIG') && !X.splitValid(1));
assert.ok(Math.abs(X.decodeSteering(32767)) < 0.01, 'steering centre decodes near zero');
assert.ok(X.decodeSteering(15222) < -770 && X.decodeSteering(15222) > -772, 'steering uses the BMW offset');
assert.ok(X.steeringQualifierValid(2) && !X.steeringQualifierValid(3));
const src = fs.readFileSync(path.join(ROOT, 'apps', 'xdrive_studio', 'main.js'), 'utf8');
assert.ok(/new ReadOnlyDiag\(/.test(src), 'transfer-case reads use the read-only link');
assert.ok(!/\.physical\(|\.functional\(|\b0x(?:2E|2F|31)\b/i.test(src), 'no writable diagnostic API or service');
const asset = JSON.parse(fs.readFileSync(path.join(ROOT, 'apps', 'xdrive_studio', 'assets', 'g12-citrin-top.json'), 'utf8'));
assert.deepStrictEqual([asset.w, asset.h], [232, 408]);
assert.strictEqual(Buffer.from(asset.rgba, 'base64').length, asset.w * asset.h * 4, 'G12 asset is complete RGBA');
assert.ok(/cv\.image\(G12_IMAGE/.test(src), 'torque page renders the G12 asset');
console.log('xDrive Studio decoder and read-only checks passed.');
