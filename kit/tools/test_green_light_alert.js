'use strict';
const assert=require('assert');
const path=require('path');
const {Controller,enumNumber,germanyResult,BERLIN_POSITION,BERLIN_NAVIGATION}=require(path.resolve(__dirname,'..','..','apps','green_light_alert','controller'));

assert.strictEqual(enumNumber('AMPEL_ROT'),12);
assert.strictEqual(enumNumber('AMPEL_GRUEN'),15);
assert.strictEqual(enumNumber({value:2}),2);
assert.ok(germanyResult(0,null).indexOf('ALREADY AVAILABLE:')===0,'an already available regional gate must not be reported as no change');
assert.ok(germanyResult(1,0).indexOf('PASS:')===0);
assert.ok(germanyResult(1,null).indexOf('INCONCLUSIVE:')===0,'a missing during-test sample must not be reported as a regional refusal');

const writes=[],calls=[];
const ctx={preview:false,log:{warn:()=>{},info:()=>{}},signals:{set:async(_p,n,v)=>writes.push([n,v]),call:async(_p,n,v)=>{calls.push([n,v]);return {SetLocationDescriptorError:0};}}};
const c=new Controller(ctx,()=>{});
c.foresightConn={available:true,proxy:{}};
c.speed=0;
c.receiveForesight({dispForesightEvent:12});
c.receiveForesight({dispForesightEvent:15});
assert.strictEqual(c.history[0].title,'GREEN LIGHT');
assert.ok(c.lastAlertAt>0);
c.receiveForesight({dispForesightEvent:14});
c.receiveForesight({dispForesightEvent:15});
assert.strictEqual(c.history.filter((e)=>e.title==='GREEN LIGHT').length,1,'yellow to green must not create an alert');

const c2=new Controller(ctx,()=>{});
c2.foresightConn={available:true,proxy:{}};
c2.speed=0;
c2.receiveForesight({dispForesightEvent:12});
c2.receiveForesight({dispForesightEvent:11});
c2.receiveForesight({dispForesightEvent:15});
assert.strictEqual(c2.history[0].title,'GREEN LIGHT','an intermediate uncertain event must not disarm a recognised red light');
c2.receiveSetting('settingTrafficlightDriveOff',{value:'ACTIVATED',availability:'OPERABLE'});
assert.strictEqual(c2.setting.value,2);
assert.strictEqual(c2.nativeState().label,'OEM ACTIVE');

const c3=new Controller(ctx,()=>{});
c3.rawConn={available:true,proxy:{}};
c3.speed=0;
c3.configureRaw(1,3);
c3.receiveRawLight({trafficLightID:7,trafficLightColor:1,trafficLightStatus:1,qualityRecognitionTrafficLight:1});
c3.receiveRawLight({trafficLightID:7,trafficLightColor:3,trafficLightStatus:1,qualityRecognitionTrafficLight:1});
assert.strictEqual(c3.history[0].title,'GREEN LIGHT','raw camera red-to-green transition must create an alert');
assert.strictEqual(c3.nativeState().label,'RAW KAFAS LIVE');

(async()=>{
    c.receiveSetting('settingTrafficlightDriveOff',{value:'ACTIVATED',availability:'OPERABLE'});
    c.settingConn={proxy:{}};
    await c.toggle();
    assert.strictEqual(writes.length,2);
    assert.strictEqual(writes[0][1].value,2);
    assert.ok(c.notice.indexOf('settingDriveOffReminder accepted')===0);
    assert.strictEqual(c.nativeState().label,'OEM ACTIVE');
    const c4=new Controller(ctx,()=>{});c4.speed=0;c4.gpsPosition={statusGPSLongitudeCAN:2100000000,statusGPSLatitudeCAN:2300000000};c4.gpsConn={proxy:{},available:true};
    c4.navLocation={coordinatesValid:true,heightValid:true,longitude:26.1,latitude:44.4,height:{unit:0,displayLength:80,rawLengthMeter:80},textDescription:{languageID:22,textDescriptorList:{}},entrancePointList:[],naviLocation:{vendorID:1,containerVersion:1,presentationArea:[],internalData:Buffer.from([1,2])},onlineId:{providerKey:'',providerId:0},heading:90,status:1};
    c4.navConn={proxy:{},available:true};
    c4.fasStatus={functionUCC:1};
    await c4.startGermanyTest();
    c4.fasStatus={functionUCC:0};
    await new Promise((resolve)=>setTimeout(resolve,800));
    const result=await c4.stopGermanyTest();
    assert.ok(result.indexOf('PASS:')===0);
    const gpsWrites=writes.filter((x)=>x[0]==='GPSPositionCAN');
    assert.deepStrictEqual(gpsWrites[0][1],BERLIN_POSITION);
    assert.deepStrictEqual(gpsWrites[gpsWrites.length-1][1],{statusGPSLongitudeCAN:2100000000,statusGPSLatitudeCAN:2300000000});
    assert.strictEqual(calls[0][0],'setCurrentLocation');
    assert.strictEqual(calls[0][1].location.latitude,BERLIN_NAVIGATION.latitude);
    assert.strictEqual(calls[0][1].location.longitude,BERLIN_NAVIGATION.longitude);
    assert.strictEqual(calls[0][1].location.heading,undefined);
    assert.ok(writes.some((x)=>x[0]==='demoModeActive'&&x[1]===true));
    assert.ok(writes.some((x)=>x[0]==='demoModeActive'&&x[1]===false));
    const moving=new Controller(ctx,()=>{});moving.speed=2;moving.gpsPosition=c4.gpsPosition;moving.gpsConn={proxy:{},available:true};moving.navLocation=c4.navLocation;moving.navConn={proxy:{},available:true};
    await assert.rejects(()=>moving.startGermanyTest(),/only while stationary/);
    console.log('Green Light Alert transition filter, provider-state and reversible Germany-context checks passed.');
})().catch((e)=>{console.error(e);process.exit(1);});
