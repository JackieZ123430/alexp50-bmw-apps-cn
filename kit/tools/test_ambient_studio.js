'use strict';
const assert = require('assert');
const os = require('os');
const fs = require('fs');
const path = require('path');
const D = require('../../apps/ambient_studio_full/catalog');
const { Controller, MIN_WRITE_MS, FLASH_MS } = require('../../apps/ambient_studio_full/controller');

assert.strictEqual(D.drivingMode({ actualValueModeDrivingExperience: 'SPORT_EXPERT' }).label, 'Sport Plus');
assert.strictEqual(D.drivingMode({ actualValueModeDrivingExperience: 10 }).name, 'ADAPTIVE');
assert.strictEqual(D.reportedColor({ statusMenuAmbientePanoramicRoofInteriorLighting: 'FARBAUSWAHL_12' }), 12);
assert.strictEqual(D.engineRunning({ statusEngineRunDrive: 'MOTOR_LAEUFT' }), true);
assert.strictEqual(D.engineRunning({ statusEngineRunDrive: 0 }), false);
assert.strictEqual(D.MODE_COLOURS.ECO_PRO_EFFICIENT, 'BLUE');
assert.strictEqual(D.MODE_COLOURS.ECO_PRO_INDIVIDUAL, 'BLUE');
assert.strictEqual(D.MODE_COLOURS.SPORT_DYNAMIC, 'RED');
assert.strictEqual(D.MODE_COLOURS.SPORT_EXPERT, 'RED');
assert.strictEqual(D.MODE_COLOURS.SPORT_INDIVIDUAL, 'RED');
assert.strictEqual(D.MODE_COLOURS.ADAPTIVE, 'GREEN');
assert.strictEqual(D.MODE_COLOURS.COMFORT_PLUS, 'ORANGE');
assert.strictEqual(D.MODE_COLOURS.COMFORT, undefined);
const req = D.colorRequest(4);
assert.strictEqual(req.controlMenuAmbientePanoramicRoofInteriorLighting, 'FARBAUSWAHL_4');
assert.strictEqual(req.controlBrightnessValueBrightnessOffsetAmbientePanoramicRoofInteriorLighting, 255);
assert.strictEqual(req.controlDynamicInteriorLighting, 'SIGNAL_UNBEFUELLT');

const off = { controlModeFunctionSpecialFlashing: 'AUS', controlPhaseFunctionSpecialFlashing: 0, alive: 2 };
const on = { controlModeFunctionSpecialFlashing: 'WARNBLINKEN', controlPhaseFunctionSpecialFlashing: 1, alive: 3 };
assert.strictEqual(D.hazardSignature(off), '{"controlModeFunctionSpecialFlashing":"AUS"}');
assert.strictEqual(D.hazardSignature(on), '{"controlModeFunctionSpecialFlashing":"WARNBLINKEN"}');

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ambient-studio-'));
const ctx = { dataDir: dir, preview: true, log: { warn() {} }, signals: { hasNative: () => false } };
const c = new Controller(ctx, () => {});
c.color = 2;
['BLUE', 'RED', 'GREEN', 'ORANGE'].forEach((name, i) => { c.color = i + 1; c.learnColor(name); });
assert.strictEqual(c.paletteReady(), true);
c.receiveMode({ actualValueModeDrivingExperience: 'SPORT_EXPERT' });
c.setModeEnabled(true);
assert.deepStrictEqual(c.desired(), { value: 2, why: 'Sport Plus -> RED', alert: null });
c.hazardRaw = D.hazardSignature(off); c.learnHazard('off');
c.hazardRaw = D.hazardSignature(on); c.learnHazard('on');
c.receiveLamp(on); c.setHazardEnabled(true); c.flashOn = true;
assert.strictEqual(c.activeAlert().key, 'hazard');
assert.strictEqual(c.desired().value, 4);
c.receiveDoor(true); c.receiveEngine({ statusEngineRunDrive: 'MOTOR_LAEUFT' }); c.setDoorEnabled(true);
assert.strictEqual(c.activeAlert().key, 'door', 'door alert has priority');
assert.strictEqual(c.desired().value, 2);
assert(MIN_WRITE_MS >= 1000 && FLASH_MS >= MIN_WRITE_MS, 'writes are conservatively paced');
c.close();
fs.rmSync(dir, { recursive: true, force: true });
console.log('Ambient Studio mapping, learning, priority and write-safety checks passed.');
